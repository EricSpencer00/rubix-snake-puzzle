#!/usr/bin/env python3
"""Generate Coq lattice checks from the shared JSON fixtures; no physical proof."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROTATIONS = ('R0', 'R90', 'R180', 'R270')


def render():
    cases = json.loads((ROOT / 'tests/fixtures/collision-models.json').read_text())
    lines = ['(* Generated by python/generate_coq_fixtures.py. *)',
             '(* These examples check only the lattice model, not physical collisions or closure. *)',
             'Require Import RubikSnake List ZArith.', 'Import ListNotations.', 'Open Scope Z_scope.', '']
    for case in cases:
        name = case['id'].replace('-', '_')
        cfg = '[' + '; '.join(ROTATIONS[r] for r in case['turns']) + ']'
        points = '[' + '; '.join(f'mkPoint ({x}) ({y}) ({z})' for x, y, z in case['lattice_positions']) + ']'
        valid = str(case['lattice_valid']).lower()
        lines += [f'Example {name}_positions : config_positions {cfg} = {points}.',
                  'Proof. reflexivity. Qed.',
                  f'Example {name}_valid : is_valid {cfg} = {valid}.',
                  'Proof. reflexivity. Qed.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'coq/CollisionFixtures.v'
    expected = render()
    if args.check:
        if destination.read_text() != expected:
            parser.exit(1, 'Coq fixture source is stale; regenerate it.\n')
        print('Coq fixture source matches shared JSON (compilation is a separate check).')
    else:
        destination.write_text(expected)
